import type { LabContent, LabDefinition } from "./types";
import { inquiryContent } from "./ramp-inquiry";

/** New stock versions only: never mutate a previously assigned worksheet. */
export function revisedContent(lab: LabDefinition): LabContent {
  const c = structuredClone(lab.content);
  c.methodology = { version: "2026-11", lab: lab.number };
  switch (lab.number) {
    case 1: {
      const v = inquiryContent(c);
      v.inquiry = "ramp-v2";
      v.questions = [c.questions[0]];
      v.notes.push(
        "Значення 0,01 с на екрані секундоміра — крок відображення, а не точність ручного вимірювання. Врахуйте реакцію під час зупинки.",
        "Для кожного обраного шляху за можливості зробіть три повтори за сталих умов. Основні три рядки порівнюють різні шляхи; повтори порівнюють однакові умови.",
        "Віртуальна модель ілюструє закладені припущення. Збіг з її формулою не є незалежним експериментальним доказом закону для реального жолоба.",
      );
      v.creative +=
        " За типових налаштувань (1,2 м, 15°, діаметр 20 мм) різниця модельного часу сталі й поліпропілену близько 0,0034 с. Вона менша за крок 0,01 с і похибку ручного відліку; не робіть висновок про матеріал з одного ручного вимірювання. Додатково: " +
        c.questions.slice(1).join(" ");
      return v;
    }
    case 9: {
      c.notes.push(
        "Запишіть ціну поділки й обґрунтовану оцінку невизначеності одного відліку. У новій моделі показ округлюється до найближчої поділки 0,2 Н: для цього правила межа округлення ±0,1 Н. Для реального приладу врахуйте також нуль, калібрування й повторюваність.",
        "Порівняйте ΔP з сумою оцінок невизначеності двох відліків (2u для однакового u). Якщо вони порівнянні, висновок про густину ненадійний. Більша різниця сама по собі не гарантує точності.",
        "Еталон моделі доступний окремо. Він не замінює спостереження й не є незалежною перевіркою формули, за якою модель побудовано.",
      );
      const e = c.experiments[0];
      e.instructions[2] =
        "Обчисліть ΔP=P₁−P₂, порівняйте її з невизначеністю відліків. Потім обчисліть густину та обґрунтуйте ймовірний матеріал; збіг із довідником сам по собі не доводить точності. Сумнівні дані збережіть із поясненням або повторіть вимірювання.";
      e.fields.splice(3, 0, {
        key: "dP",
        label: "Різниця показів",
        unit: "Н",
        positive: true,
        calculated: { op: "subtract", args: ["P1", "P2"] },
      });
      return c;
    }
    case 10:
      c.notes.push(
        "Назва рядка — запланована умова, а не готовий результат. Записуйте фактичне спостереження. Якщо потрібного стану не отримано, повторіть дослід або поясніть невідповідність, зберігши вихідні дані.",
        "Нейтральність у моделі точна; у реальному досліді її встановлюють наближено з урахуванням невизначеності маси й об’єму та повільного руху. Невелика різниця обчислених густин не замінює спостереження.",
        "Для схеми потопання розглядайте тіло у воді до контакту з дном: mg>FА, N=0. Для спокою на дні: mg=FА+N. На поверхні у спокої FА=mg, занурений об’єм менший за повний.",
        "Результати моделі показують наслідки її припущень; для перевірки реальних тіл потрібні незалежні вимірювання.",
      );
      c.experiments[0].instructions.push(
        "Перед переходом до висновку перевірте: зовнішній об’єм у трьох рядках сталий, змінюється лише маса піску, а спостереження відповідають досліджуваним станам. Попередження не виправляє ваші числа автоматично.",
      );
      return c;
    default:
      throw new Error("На першому етапі оновлюються лише роботи №1, №9 і №10.");
  }
}
